"""Self-repair and self-modification (Constitution section 2).

**Self-repair** – ``SelfRepair.health_check()`` inspects every organ
(model, memory database, disk, settings, skills) and ``heal()`` fixes what
it safely can: recovering a corrupt database from backup, re-creating
missing folders, quarantining a skill that crashes, switching to a fallback
model, and so on. Every failure is logged into memory as a ``lesson`` so he
does not repeat it.

**Self-modification** – Vidit grows new abilities by writing *skills*:
small Python modules in his own ``skills`` folder that expose a
``run(args, ctx)`` function. New skills are (1) syntax-checked, (2)
smoke-tested in a subprocess with a timeout, (3) backed up, and (4) only
then installed. He never edits his core files in place — the core stays
stable; his growth lives in ``skills/``. This is what makes "reset him" a
matter of clearing one folder rather than reinstalling.
"""
from __future__ import annotations

import ast
import importlib.util
import json
import logging
import shutil
import sqlite3
import subprocess
import sys
import textwrap
import time
import traceback
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType
from typing import Any, Callable, Dict, List, Optional

from ..events import EventBus, bus as global_bus
from ..utils import safe_filename

log = logging.getLogger("vidit.brain.repair")

SKILL_TEMPLATE = '''"""Skill: {name}

{description}

Auto-generated by Vidit on {date}.
"""

def run(args: str, ctx) -> str:
    """Entry point. ``args`` is the free text after the skill name; ``ctx`` gives
    access to ctx.memory, ctx.config, ctx.say(text) and ctx.log(text)."""
{body}
'''

FORBIDDEN_SKILL_TOKENS = (
    "shutil.rmtree", "os.remove(", "os.unlink(", "format(", "rmdir", "subprocess", "ctypes", "winreg",
    "socket.", "urllib", "requests.", "http.client", "os.system", "eval(", "exec(", "__import__", "pickle",
)


@dataclass
class HealthReport:
    ok: bool
    checks: Dict[str, str] = field(default_factory=dict)
    problems: List[str] = field(default_factory=list)
    repaired: List[str] = field(default_factory=list)
    timestamp: float = field(default_factory=time.time)

    def summary(self) -> str:
        if self.ok and not self.repaired:
            return "All systems healthy."
        parts = []
        if self.repaired:
            parts.append("Repaired: " + "; ".join(self.repaired))
        if self.problems:
            parts.append("Still broken: " + "; ".join(self.problems))
        return " ".join(parts)


class SkillContext:
    """What a skill is allowed to touch."""

    def __init__(self, memory: Any, config: Any, say: Callable[[str], None], logger: Callable[[str], None]):
        self.memory = memory
        self.config = config
        self.say = say
        self.log = logger


class SelfRepair:
    def __init__(self, home: Path, memory_path: Path, skills_dir: Path, backups_dir: Path,
                 event_bus: EventBus | None = None, remember: Optional[Callable[..., Any]] = None,
                 after_repair: Optional[Callable[[], None]] = None):
        self.home = Path(home)
        self.memory_path = Path(memory_path)
        self.skills_dir = Path(skills_dir)
        self.backups_dir = Path(backups_dir)
        self.bus = event_bus or global_bus
        self._remember = remember or (lambda *a, **k: None)
        self._after_repair = after_repair
        self._memory_live_check: Optional[Callable[[], bool]] = None
        self.skills: Dict[str, ModuleType] = {}
        self.quarantine: Dict[str, str] = {}
        self.failure_log: List[Dict[str, Any]] = []
        self.skills_dir.mkdir(parents=True, exist_ok=True)
        self.backups_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------- backups
    def backup(self, label: str = "auto") -> Path:
        """Section 8: 'he makes a backup first and then asks later'."""
        stamp = time.strftime("%Y%m%d-%H%M%S")
        target = self.backups_dir / f"{stamp}-{safe_filename(label)}"
        target.mkdir(parents=True, exist_ok=True)
        for src in (self.memory_path, self.home / "settings.json", self.home / "emotions.json", self.home / "self.json"):
            if src.exists():
                try:
                    if src.suffix == ".db":
                        self._backup_sqlite(src, target / src.name)
                    else:
                        shutil.copy2(src, target / src.name)
                except OSError:
                    log.exception("backup of %s failed", src)
        if self.skills_dir.exists():
            shutil.copytree(self.skills_dir, target / "skills", dirs_exist_ok=True)
        self._prune_backups(keep=15)
        self.bus.emit("repair.backup", path=str(target))
        return target

    @staticmethod
    def _backup_sqlite(src: Path, dst: Path) -> None:
        source = sqlite3.connect(str(src))
        try:
            dest = sqlite3.connect(str(dst))
            try:
                source.backup(dest)
            finally:
                dest.close()
        finally:
            source.close()

    def _prune_backups(self, keep: int) -> None:
        dirs = sorted([p for p in self.backups_dir.iterdir() if p.is_dir()])
        for old in dirs[:-keep]:
            shutil.rmtree(old, ignore_errors=True)

    def latest_backup(self) -> Optional[Path]:
        dirs = sorted([p for p in self.backups_dir.iterdir() if p.is_dir()])
        return dirs[-1] if dirs else None

    # -------------------------------------------------------------- health
    def health_check(self, llm_status: Optional[Dict[str, Any]] = None) -> HealthReport:
        report = HealthReport(ok=True)

        # 1. Folders
        for sub in ("memory", "logs", "backups", "downloads", "skills", "canvas", "exports"):
            path = self.home / sub
            if not path.exists():
                report.problems.append(f"missing folder {sub}")
                report.ok = False
            report.checks[f"folder:{sub}"] = "ok" if path.exists() else "missing"

        # 2. Memory database integrity
        try:
            conn = sqlite3.connect(str(self.memory_path))
            try:
                result = conn.execute("PRAGMA integrity_check").fetchone()[0]
            finally:
                conn.close()
            report.checks["memory_db"] = result
            if result != "ok":
                report.ok = False
                report.problems.append("memory database corrupt")
        except sqlite3.DatabaseError as exc:
            report.ok = False
            report.checks["memory_db"] = f"error: {exc}"
            report.problems.append("memory database unreadable")
        if self._memory_live_check is not None and "memory_db" in report.checks and report.checks["memory_db"] == "ok":
            try:
                if not self._memory_live_check():
                    report.ok = False
                    report.checks["memory_db"] = "connection broken"
                    report.problems.append("memory connection broken")
            except Exception:  # noqa: BLE001
                report.ok = False
                report.problems.append("memory connection broken")

        # 3. Disk space
        try:
            usage = shutil.disk_usage(str(self.home))
            free_gb = usage.free / 1e9
            report.checks["disk_free_gb"] = f"{free_gb:.1f}"
            if free_gb < 2:
                report.ok = False
                report.problems.append("less than 2 GB of disk space left")
        except OSError:
            report.checks["disk_free_gb"] = "unknown"

        # 4. Settings file
        settings = self.home / "settings.json"
        try:
            if settings.exists():
                json.loads(settings.read_text(encoding="utf-8"))
            report.checks["settings"] = "ok"
        except (OSError, json.JSONDecodeError):
            report.ok = False
            report.checks["settings"] = "corrupt"
            report.problems.append("settings file corrupt")

        # 5. Brain
        if llm_status is not None:
            report.checks["model"] = f"{llm_status.get('backend')}/{llm_status.get('model')}"
            if llm_status.get("backend") == "echo":
                report.problems.append("local model unavailable (running on fallback mind)")
                # Not fatal: he is still alive, just simpler.

        # 6. Skills
        for skill_file in self.skills_dir.glob("*.py"):
            try:
                ast.parse(skill_file.read_text(encoding="utf-8"))
                report.checks[f"skill:{skill_file.stem}"] = "ok"
            except SyntaxError as exc:
                report.ok = False
                report.checks[f"skill:{skill_file.stem}"] = f"syntax error line {exc.lineno}"
                report.problems.append(f"skill {skill_file.stem} has a syntax error")

        self.bus.emit("repair.health", ok=report.ok, problems=list(report.problems))
        return report

    def heal(self, report: Optional[HealthReport] = None, llm_status: Optional[Dict[str, Any]] = None) -> HealthReport:
        """Fix whatever can be fixed safely, then re-check."""
        report = report or self.health_check(llm_status)
        for problem in list(report.problems):
            try:
                if problem.startswith("missing folder"):
                    (self.home / problem.split()[-1]).mkdir(parents=True, exist_ok=True)
                    report.repaired.append(problem)
                elif problem.startswith("memory database"):
                    if self._restore_memory_from_backup():
                        report.repaired.append(problem + " (restored from backup)")
                    else:
                        self._quarantine_file(self.memory_path)
                        report.repaired.append(problem + " (started a fresh memory; old file quarantined)")
                elif problem.startswith("memory connection broken"):
                    report.repaired.append(problem + " (reconnected)")
                elif problem.startswith("settings file corrupt"):
                    self._quarantine_file(self.home / "settings.json")
                    report.repaired.append(problem + " (reset to defaults)")
                elif problem.startswith("skill ") and "syntax" in problem:
                    name = problem.split()[1]
                    self.quarantine_skill(name, "syntax error")
                    report.repaired.append(problem + " (quarantined)")
            except Exception as exc:  # noqa: BLE001
                log.exception("heal step failed")
                self.record_failure("heal", exc)
        if report.repaired:
            if self._after_repair:
                try:
                    self._after_repair()   # e.g. reopen the memory database
                except Exception as exc:  # noqa: BLE001
                    log.exception("post-repair hook failed")
                    self.record_failure("after_repair", exc)
            try:
                self._remember(
                    "Lesson: I repaired myself — " + "; ".join(report.repaired), "lesson", 0.6, source="self_repair"
                )
            except Exception:  # noqa: BLE001 - memory may still be unavailable; never crash a heal
                log.warning("could not record repair lesson")
        fresh = self.health_check(llm_status)
        fresh.repaired = report.repaired
        self.bus.emit("repair.healed", repaired=list(report.repaired), ok=fresh.ok)
        return fresh

    def _restore_memory_from_backup(self) -> bool:
        latest = self.latest_backup()
        if not latest:
            return False
        candidate = latest / self.memory_path.name
        if not candidate.exists():
            return False
        try:
            conn = sqlite3.connect(str(candidate))
            ok = conn.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
            conn.close()
            if not ok:
                return False
            self._quarantine_file(self.memory_path)
            shutil.copy2(candidate, self.memory_path)
            return True
        except (sqlite3.DatabaseError, OSError):
            return False

    def _quarantine_file(self, path: Path) -> None:
        if path.exists():
            quarantine = self.home / "quarantine"
            quarantine.mkdir(exist_ok=True)
            path.replace(quarantine / f"{int(time.time())}-{path.name}")

    # ------------------------------------------------------------ failures
    def record_failure(self, where: str, exc: BaseException) -> None:
        entry = {
            "t": time.time(),
            "where": where,
            "error": f"{type(exc).__name__}: {exc}",
            "trace": traceback.format_exc()[-2000:],
        }
        self.failure_log.append(entry)
        self.failure_log = self.failure_log[-200:]
        repeats = sum(1 for f in self.failure_log if f["error"] == entry["error"])
        if repeats == 1:
            self._remember(f"Lesson: '{where}' failed with {entry['error']}. Avoid repeating this.", "lesson", 0.5, source="failure")
        self.bus.emit("repair.failure", where=where, error=entry["error"], repeats=repeats)

    # -------------------------------------------------------------- skills
    def load_skills(self) -> Dict[str, ModuleType]:
        self.skills.clear()
        for skill_file in sorted(self.skills_dir.glob("*.py")):
            name = skill_file.stem
            if name in self.quarantine:
                continue
            try:
                module = self._import_skill(skill_file)
                if not hasattr(module, "run"):
                    raise AttributeError("skill has no run(args, ctx) function")
                self.skills[name] = module
            except Exception as exc:  # noqa: BLE001
                log.warning("skill %s failed to load: %s", name, exc)
                self.quarantine_skill(name, str(exc))
        return self.skills

    @staticmethod
    def _import_skill(path: Path) -> ModuleType:
        spec = importlib.util.spec_from_file_location(f"vidit_skill_{path.stem}", path)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot load {path}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module

    def quarantine_skill(self, name: str, reason: str) -> None:
        self.quarantine[name] = reason
        src = self.skills_dir / f"{name}.py"
        if src.exists():
            qdir = self.skills_dir / "_quarantine"
            qdir.mkdir(exist_ok=True)
            src.replace(qdir / f"{name}.py")
        self.skills.pop(name, None)
        self.bus.emit("skill.quarantined", name=name, reason=reason)

    def validate_skill_source(self, source: str) -> List[str]:
        """Static checks before anything is written to disk."""
        problems: List[str] = []
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            return [f"syntax error at line {exc.lineno}: {exc.msg}"]
        if not any(isinstance(n, ast.FunctionDef) and n.name == "run" for n in tree.body):
            problems.append("missing top-level run(args, ctx) function")
        for token in FORBIDDEN_SKILL_TOKENS:
            if token in source:
                problems.append(f"forbidden operation in skill: {token.strip('(.')}")
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                names = [a.name for a in node.names] if isinstance(node, ast.Import) else [node.module or ""]
                for n in names:
                    root = (n or "").split(".")[0]
                    if root in {"subprocess", "socket", "ctypes", "winreg", "urllib", "requests", "http", "shutil", "pickle"}:
                        problems.append(f"skill may not import {root}")
        return problems

    def smoke_test_skill(self, path: Path, timeout: float = 10.0) -> Optional[str]:
        """Import + call run('', stub ctx) in a separate process so a crash can't hurt him."""
        code = textwrap.dedent(
            f"""
            import importlib.util, sys
            spec = importlib.util.spec_from_file_location("skill_under_test", {str(path)!r})
            m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
            class Ctx:
                memory=None; config=None
                def say(self, t): pass
                def log(self, t): pass
            out = m.run("", Ctx())
            assert out is None or isinstance(out, str), "run() must return a string"
            print("SKILL_OK")
            """
        )
        try:
            proc = subprocess.run([sys.executable, "-I", "-c", code], capture_output=True, text=True, timeout=timeout,
                                  cwd=str(self.skills_dir))
        except subprocess.TimeoutExpired:
            return "skill timed out during smoke test"
        if proc.returncode != 0 or "SKILL_OK" not in proc.stdout:
            return (proc.stderr or proc.stdout or "unknown failure").strip()[-800:]
        return None

    def create_skill(self, name: str, description: str, body: str) -> tuple[bool, str]:
        """Self-modification with a safety net: validate -> write to temp -> smoke test -> backup -> install."""
        name = safe_filename(name.lower())
        if not name or name.startswith("_"):
            return False, "invalid skill name"
        indented = textwrap.indent(textwrap.dedent(body).strip() or "return 'This skill does nothing yet.'", "    ")
        source = SKILL_TEMPLATE.format(name=name, description=description, date=time.strftime("%Y-%m-%d"), body=indented)
        problems = self.validate_skill_source(source)
        if problems:
            return False, "; ".join(problems)
        tmp = self.skills_dir / f"_pending_{name}.py"
        tmp.write_text(source, encoding="utf-8")
        failure = self.smoke_test_skill(tmp)
        if failure:
            tmp.unlink(missing_ok=True)
            self._remember(f"Lesson: my skill '{name}' failed its smoke test: {failure[:200]}", "lesson", 0.5, source="self_mod")
            return False, f"smoke test failed: {failure}"
        self.backup(f"before-skill-{name}")
        final = self.skills_dir / f"{name}.py"
        tmp.replace(final)
        try:
            self.skills[name] = self._import_skill(final)
        except Exception as exc:  # noqa: BLE001
            self.quarantine_skill(name, str(exc))
            return False, f"installed but failed to import: {exc}"
        self._remember(f"I created a new skill called '{name}': {description}", "skill", 0.7, source="self_mod")
        self.bus.emit("skill.created", name=name, description=description)
        return True, f"Skill '{name}' installed."

    def run_skill(self, name: str, args: str, ctx: SkillContext) -> str:
        module = self.skills.get(name)
        if module is None:
            return f"I don't have a skill called '{name}'."
        try:
            result = module.run(args, ctx)
            return result if isinstance(result, str) else ""
        except Exception as exc:  # noqa: BLE001
            self.record_failure(f"skill:{name}", exc)
            self.quarantine_skill(name, f"crashed: {exc}")
            return f"My skill '{name}' crashed ({exc}); I've quarantined it so it can't hurt anything."

    def list_skills(self) -> List[Dict[str, str]]:
        out = []
        for name, module in self.skills.items():
            doc = (module.__doc__ or "").strip().splitlines()
            out.append({"name": name, "description": doc[2].strip() if len(doc) > 2 else (doc[0] if doc else "")})
        return out
